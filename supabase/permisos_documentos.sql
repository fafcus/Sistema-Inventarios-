-- ============================================================
-- PERMISOS POR DOCUMENTO / INVENTARIO
-- Sistema Inventarios - Supabase
--
-- Ejecutar una vez en Supabase > SQL Editor.
-- Esta migración agrega permisos por usuario y documento y
-- refuerza el acceso con Row Level Security (RLS).
